// Write the backfilled Telugu translations into te.ts, then validate:
//  - key parity with en.ts
//  - every {placeholder} from en appears in te
//  - values contain Telugu script (or are allowlisted format tokens)
import { promises as fs } from "fs";
import * as path from "path";
import * as url from "url";

const ROOT = path.join(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const EN_PATH = path.join(ROOT, "src/lib/i18n/en.ts");
const TE_PATH = path.join(ROOT, "src/lib/i18n/te.ts");
const PROGRESS = path.join(ROOT, "scripts/.te-backfill-progress.json");

function parseDict(src, name) {
  const start = src.indexOf(`export const ${name}: Record<string, string> = {`);
  const o = src.indexOf("{", start);
  const e = src.lastIndexOf("};");
  return eval("(" + src.slice(o, e + 1).replace(/;$/, "") + ")");
}

const en = parseDict(await fs.readFile(EN_PATH, "utf8"), "en");
const te = parseDict(await fs.readFile(TE_PATH, "utf8"), "te");
const done = JSON.parse(await fs.readFile(PROGRESS, "utf8"));

// Merge backfilled translations (never downgrade a real translation to English)
for (const [k, v] of Object.entries(done)) {
  if (!(k in en)) continue;
  if (typeof v === "string" && v.length > 0) te[k] = v;
}

const allowFormat = /^[-+·•.,:;()%\s{}"']*(FP|pts?|MRP|₹|Koino)?[-+·•.,:;()%\s{}"']*$/i;
const allowExact = /^(Koino|KJV|WEB|FP|MRP|ESV|WhatsApp|India|https?:\/\/\S+|\+91…?|\{[a-z]+\}(…|\.\.\.)?)$/i;

// Corrections for issues found in validation (broken placeholders / Latin leftovers)
const patches = {
  "bible.streak.nDaysDesc": "మీరు {n} రోజుల పాటు వరుసగా బైబిల్ చదువుతున్నారు. కొనసాగించండి!",
  "apologetics.searchPlaceholder": "{articles} వెతకండి...",
  "marketplace.listModal.mrp": "MRP (ఐచ్ఛికం)",
  "marketplace.listModal.whatsapp": "WhatsApp నంబర్ *",
  "churches.form.serviceTimePlaceholder": "8:00 AM - 11:00 AM",
};
for (const [k, v] of Object.entries(patches)) if (k in en) te[k] = v;
// Drop dead keys that no longer exist in en.ts
for (const k of Object.keys(te)) if (!(k in en)) delete te[k];

const missing = [], placeholderIssues = [], notTranslated = [];
const placeholderRe = /\{([^}]+)\}/g;
for (const [k, enV] of Object.entries(en)) {
  const teV = te[k];
  if (teV === undefined || teV === "") { missing.push(k); continue; }
  const enVars = enV.match(placeholderRe) || [];
  const teVars = teV.match(placeholderRe) || [];
  for (const v of enVars) {
    if (!teVars.includes(v)) { placeholderIssues.push(`${k}: ${v} (en) not in te "${teV}"`); break; }
  }
  if (!/[\u0C00-\u0C7F]/.test(teV) && /[A-Za-z]{2,}/.test(teV) && !allowFormat.test(teV) && !allowExact.test(teV) && teV === enV) {
    notTranslated.push(k);
  }
}

const extra = Object.keys(te).filter((k) => !(k in en));
console.log(`te: ${Object.keys(te).length} keys | en: ${Object.keys(en).length}`);
console.log(`missing: ${missing.length}${missing.length ? " → " + missing.join(", ") : ""}`);
console.log(`placeholderIssues: ${placeholderIssues.length}${placeholderIssues.length ? "\n  " + placeholderIssues.slice(0, 12).join("\n  ") : ""}`);
console.log(`untranslated-remaining: ${notTranslated.length}${notTranslated.length ? " → " + notTranslated.join(", ") : ""}`);
console.log(`extra-vs-en: ${extra.length}${extra.length ? " → " + extra.join(", ") : ""}`);

if (process.env.WRITE !== "1") { console.log("(dry run — set WRITE=1 to write te.ts)"); process.exit(0); }

const order = Object.keys(en); // align key order with en.ts for diff friendliness
const lines = [];
for (const k of order) {
  const esc = String(te[k] ?? en[k]).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
  lines.push(`  "${k}": "${esc}",`);
}

const header = `// Telugu (తెలుగు) — complete website translation.
//
// Coverage: every en.ts key has a Telugu value. Generated by the translation
// pipeline (scripts/i18n-backfill-te.mjs + manual curation) using the project
// Christian glossary: Bible=బైబిల్, prayer=ప్రార్థన, church=చర్చి, faith=విశ్వాసం,
// fellowship=సహవాసం, worship=ఆరాధన, gospel=సువార్త, salvation=రక్షణ, grace=కృప,
// verse=వచనం, chapter=అధ్యాయం, testimony=సాక్ష్యం, community=సంఘం.
// App vocabulary: post=పోస్ట్, follow=ఫాలో, followers=ఫాలోవర్స్,
// notifications=నోటిఫికేషన్లు, groups=గ్రూపులు, marketplace=మార్కెట్‌ప్లేస్,
// trivia=ట్రివియా, comics=కామిక్స్, profile=ప్రొఫైల్, FP=FP.
// Brand names (Koino, WhatsApp, YouTube, UPI…) and {placeholders} are preserved
// untranslated. Bible scripture text itself is English (KJV/WEB) — only the
// application interface is localized here.

export const te: Record<string, string> = {
${lines.join("\n")}
};

export default te;
`;
await fs.writeFile(TE_PATH, header);
console.log(`te.ts written with ${order.length} keys.`);
