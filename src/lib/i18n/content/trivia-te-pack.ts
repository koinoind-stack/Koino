// Static Telugu content pack for TriviaQuestion content.
//
// WHY: trivia questions live in the production DB. The existing multilingual
// solution (`TriviaQuestion.translations` JSON column + offline ZAI batches)
// only serves Telugu if someone writes translations into the production DB —
// which is out of scope/safe-mode for this project phase. This pack ships the
// Telugu question/options/explanation content as a build-time JSON file and is
// used by /api/trivia/start as a code-level fallback (DB translation wins if
// present). No runtime translation calls, no production data changes.
//
// Generated by scripts/build-trivia-te-pack.ts (validated: Telugu script,
// option-count parity per question). English fallback remains for any
// question missing from the pack.

import raw from "./trivia-te.json";

export type TriviaTeEntry = { q: string; options: string[]; explanation: string };

const entries = (raw as { entries: Record<string, TriviaTeEntry> }).entries ?? {};

export function getTriviaTePack(): Record<string, TriviaTeEntry> {
  return entries;
}

export function triviaTeCoverage(): number {
  return Object.keys(entries).length;
}
