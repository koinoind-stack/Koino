/**
 * Localized display name for a Bible book in the given Koino UI language.
 * Falls back to the English name whenever no translation is available.
 */
export function localizedBookName(
  book: { id: string; name: string },
  uiLang: string
): string {
  const bySlug = LOCALIZED_BOOK_NAMES[uiLang];
  if (!bySlug) return book.name;
  return bySlug[book.id] || book.name;
}
